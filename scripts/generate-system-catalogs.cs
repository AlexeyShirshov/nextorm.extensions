#!/usr/bin/env dotnet
#:include ../src/Generators/RepositoryContextSource.cs

using System.Text;
using Nextorm.Contexts;

var root = args.Length == 1 ? Path.GetFullPath(args[0]) : Directory.GetCurrentDirectory();

// The projection includes columns used in SELECT, JOIN, WHERE and ORDER BY.
Generate("PostgreSql", "pg_catalog", """
    pg_class PgClass oid:uint relnamespace:uint relname:string relkind:char
    pg_namespace PgNamespace oid:uint nspname:string
    pg_attribute PgAttribute attrelid:uint attname:string atttypid:uint atttypmod:int attnum:short attisdropped:bool attnotnull:bool
    pg_type PgType oid:uint typnamespace:uint typname:string
    pg_index PgIndex indrelid:uint indisprimary:bool indkey:short[] indnkeyatts:short
    """);

Generate("SqlServer", "sys", """
    objects SysObject object_id:int schema_id:int name:string type:string is_ms_shipped:bool
    schemas SysSchema schema_id:int name:string
    columns SysColumn object_id:int column_id:int name:string user_type_id:int is_nullable:bool precision:byte scale:byte max_length:short
    types SysType user_type_id:int schema_id:int name:string is_user_defined:bool is_assembly_type:bool
    indexes SysIndex object_id:int index_id:int is_primary_key:bool
    index_columns SysIndexColumn object_id:int index_id:int column_id:int key_ordinal:byte
    """);

void Generate(string provider, string schema, string catalog)
{
    var source = new StringBuilder($"// <auto-generated/>\n#nullable enable\nnamespace {provider}DatabaseMappings;\n");
    var tables = catalog.Split('\n').Select(line => line.Split(' ', StringSplitOptions.RemoveEmptyEntries)).ToArray();
    RepositoryContextSource.Append(source, $"{provider}RepositoryContext", tables.Select(table => table[1]));
    foreach (var table in tables)
    {
        source.Append($"\n[global::System.ComponentModel.DataAnnotations.Schema.Table(\"{table[0]}\", Schema = \"{schema}\")]\n");
        source.Append($"internal class {table[1]}\n{{\n");
        foreach (var field in table.Skip(2))
        {
            var parts = field.Split(':');
            var name = string.Concat(parts[0].Split('_').Select(word => char.ToUpperInvariant(word[0]) + word[1..]));
            var initializer = parts[1] switch
            {
                "string" => " = null!;",
                "short[]" => " = [];",
                _ => ""
            };
            source.Append($"    [global::System.ComponentModel.DataAnnotations.Schema.Column(\"{parts[0]}\")]\n");
            source.Append($"    public {parts[1]} {name} {{ get; set; }}{initializer}\n");
        }
        source.Append("}\n");
    }
    File.WriteAllText(Path.Combine(root, "src", "Generators", $"Nextorm.Contexts.{provider}", "Generated", "RepositoryContext.cs"), source.ToString());
}
