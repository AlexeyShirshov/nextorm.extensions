using System.Globalization;
using System.Text;
using Microsoft.Data.Sqlite;

namespace Nextorm.Contexts.Sqlite;

public static class SqliteSchemaGenerator
{
    public static void Generate(string databasePath, string outputPath)
    {
        using var connection = new SqliteConnection(new SqliteConnectionStringBuilder
        {
            DataSource = Path.GetFullPath(databasePath),
            Mode = SqliteOpenMode.ReadOnly,
            Pooling = false
        }.ToString());
        connection.Open();
        using var transaction = connection.BeginTransaction(deferred: true);
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace DatabaseMappings;\n");
        using var objects = connection.CreateCommand();
        objects.Transaction = transaction;
        objects.CommandText = """
            SELECT name, type FROM pragma_table_list
            WHERE schema = 'main' AND type IN ('table', 'view', 'virtual')
              AND substr(name, 1, 7) <> 'sqlite_'
            ORDER BY name COLLATE BINARY
            """;
        using var rows = objects.ExecuteReader();
        var objectIndex = 0;
        while (rows.Read())
        {
            var name = rows.GetString(0);
            source.Append(CultureInfo.InvariantCulture, $$"""

                [global::System.ComponentModel.DataAnnotations.Schema.Table({{Literal(name)}})]
                internal sealed class Object{{++objectIndex}}
                {

                """);
            using var columns = connection.CreateCommand();
            columns.Transaction = transaction;
            columns.CommandText = """
                SELECT cid, name, type, "notnull", pk FROM pragma_table_xinfo($name, 'main')
                ORDER BY cid
                """;
            columns.Parameters.AddWithValue("$name", name);
            using var metadata = columns.ExecuteReader();
            while (metadata.Read())
            {
                var columnName = metadata.GetString(1);
                var declared = metadata.GetString(2);
                var type = declared.Trim().ToUpperInvariant() switch
                {
                    "INTEGER" or "INT" or "BIGINT" or "SMALLINT" or "TINYINT" => "long",
                    "REAL" or "DOUBLE" or "DOUBLE PRECISION" or "FLOAT" => "double",
                    "TEXT" => "string",
                    "BLOB" => "byte[]",
                    _ => throw new InvalidDataException(
                        $"SQLite object {Literal(name)}, column {Literal(columnName)}: unsupported schema type {Literal(declared)}.")
                };
                // SQLite permits NULL in some declared primary keys; do not infer NOT NULL from pk.
                var suffix = metadata.GetInt64(3) == 0 ? "?" : "";
                var initializer = suffix.Length == 0 && type is "string" or "byte[]" ? " = null!;" : "";
                var keyOrdinal = metadata.GetInt64(4);
                if (keyOrdinal > 0 && rows.GetString(1) != "view")
                    source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
                source.Append(CultureInfo.InvariantCulture,
                    $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(columnName)}, Order = {metadata.GetInt64(0)}, TypeName = {Literal(declared)})]\n" +
                    $"    public {type}{suffix} Column{metadata.GetInt64(0)} {{ get; set; }}{initializer}\n");
            }
            source.Append("}\n");
        }
        rows.Close();
        transaction.Commit();

        // Publish one complete file only after every column has been validated.
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));
        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            using (var writer = new StreamWriter(stream))
                writer.Write(source.ToString());
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            File.Delete(temporary);
        }
    }

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
