using System.Data.Common;
using System.Globalization;
using System.Text;
using Microsoft.Data.SqlClient;
using Nextorm.Scaffold;

namespace Nextorm.Contexts.SqlServer;

public static class SqlServerSchemaGenerator
{
    public static void Scaffold(string connectionString, string outputPath, string targetNamespace, string contextName,
        IScaffoldInterceptor interceptor, bool singleFile = false, Func<string, bool>? includeSchema = null)
    {
        using var connection = new SqlConnection(connectionString);
        connection.Open();
        using var metadata = SqlServerCatalog.Read(connection);
        using var reader = metadata.CreateDataReader();
        WriteMappings(reader, outputPath, true, targetNamespace, contextName, interceptor, singleFile, includeSchema);
    }

    public static void Generate(string connectionString, string outputPath)
    {
        using var connection = new SqlConnection(connectionString);
        connection.Open();
        using var metadata = SqlServerCatalog.Read(connection);
        using var reader = metadata.CreateDataReader();
        WriteMappings(reader, outputPath, hasCatalogKind: true);
    }

    internal static void WriteMappings(DbDataReader metadata, string outputPath) =>
        WriteMappings(metadata, outputPath, hasCatalogKind: false);

    private static void WriteMappings(DbDataReader metadata, string outputPath, bool hasCatalogKind,
        string targetNamespace = "SqlServerDatabaseMappings", string contextName = "SqlServerRepositoryContext",
        IScaffoldInterceptor? interceptor = null, bool singleFile = false, Func<string, bool>? includeSchema = null)
    {
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var source = new StringBuilder($"// <auto-generated/>\n#nullable enable\nnamespace {targetNamespace};\n");
        var mappings = new List<string>();
        var usedNames = new HashSet<string>(StringComparer.Ordinal) { contextName, "Repository" };
        var usedProperties = new HashSet<string>(StringComparer.Ordinal);
        var visibility = interceptor is null ? "internal" : "public";
        int? previous = null;
        var included = false;
        var objectNumber = 0;
        var columnNumber = 0;
        while (metadata.Read())
        {
            var id = metadata.GetInt32(0);
            var schema = metadata.GetString(1);
            var name = metadata.GetString(2);
            if (id != previous)
            {
                if (included)
                    FinishObject();
                previous = id;
                included = (includeSchema?.Invoke(schema) ?? true) && (interceptor?.IncludeObject(name) ?? true);
                if (!included)
                    continue;
                columnNumber = 0;
                var mapping = interceptor is null
                    ? FormattableString.Invariant($"Object{++objectNumber}")
                    : RepositoryContextSource.Identifier(interceptor.GetEntityName(name), "Entity", usedNames);
                mappings.Add(mapping);
                usedProperties.Clear();
                usedProperties.Add(mapping);
                if (hasCatalogKind)
                {
                    var kind = metadata.GetString(12).TrimEnd() switch
                    {
                        "U" => "TABLE",
                        "V" => "VIEW",
                        "ET" => "EXTERNAL TABLE",
                        _ => throw new InvalidDataException("Unexpected SQL Server catalog object kind.")
                    };
                    source.Append(CultureInfo.InvariantCulture,
                        $"\n[global::System.ComponentModel.Description({Literal("SQL Server " + kind)})]");
                }
                source.Append(CultureInfo.InvariantCulture,
                    $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(name)}, Schema = {Literal(schema)})]\n{visibility} class {mapping}\n{{\n");
            }

            if (!included || metadata.IsDBNull(3))
                continue;

            var column = metadata.GetString(3);
            var typeName = metadata.IsDBNull(5) ? "<unresolved catalog type>" : metadata.GetString(5);
            var precision = metadata.GetByte(7);
            var scale = metadata.GetByte(8);
            var length = metadata.GetInt16(9);
            var custom = metadata.GetBoolean(11);
            var declaration = custom ? $"{metadata.GetString(4)}.{typeName}" : typeName switch
            {
                "decimal" or "numeric" => FormattableString.Invariant($"{typeName}({precision},{scale})"),
                "datetime2" or "datetimeoffset" or "time" => FormattableString.Invariant($"{typeName}({scale})"),
                "nvarchar" or "nchar" => length < 0 ? $"{typeName}(max)" : FormattableString.Invariant($"{typeName}({length / 2})"),
                "varchar" or "char" or "varbinary" or "binary" => length < 0 ? $"{typeName}(max)" : FormattableString.Invariant($"{typeName}({length})"),
                _ => typeName
            };
            var type = interceptor?.GetClrType(column, declaration) ?? ((custom ? "" : typeName) switch
            {
                "bit" => "bool",
                "tinyint" => "byte",
                "smallint" => "short",
                "int" => "int",
                "bigint" => "long",
                "real" => "float",
                "float" => "double",
                "money" or "smallmoney" => "decimal",
                "decimal" or "numeric" when precision <= 28 => "decimal",
                "char" or "varchar" or "text" or "nchar" or "nvarchar" or "ntext" => "string",
                "binary" or "varbinary" or "image" or "timestamp" or "rowversion" => "byte[]",
                "uniqueidentifier" => "global::System.Guid",
                "date" or "datetime" or "datetime2" or "smalldatetime" => "global::System.DateTime",
                "datetimeoffset" => "global::System.DateTimeOffset",
                "time" => "global::System.TimeSpan",
                _ => throw new InvalidDataException(
                    $"SQL Server object {Literal(schema)}.{Literal(name)}, column {Literal(column)}: unsupported schema type {Literal(declaration)}.")
            });
            var nullable = metadata.GetBoolean(6);
            var suffix = nullable ? "?" : "";
            var initializer = !nullable && type is "string" or "byte[]" ? " = null!;" : "";
            var keyOrdinal = metadata.GetInt32(10);
            if (keyOrdinal > 0)
            {
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            }
            var property = interceptor is null
                ? FormattableString.Invariant($"Column{++columnNumber}")
                : RepositoryContextSource.Identifier(interceptor.GetPropertyName(name, column), "Field", usedProperties);
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column)}, TypeName = {Literal(declaration)})]\n    public {type}{suffix} {property} {{ get; set; }}{initializer}\n");
        }

        if (included)
            FinishObject();

        if (interceptor is not null && mappings.Count == 0)
            throw new InvalidDataException("No SQL Server objects matched the scaffold filters.");
        RepositoryContextSource.Append(source, contextName, mappings, interceptor is not null);
        if (interceptor is not null && !singleFile)
        {
            RepositoryContextFiles.Split(source.ToString(), destination);
            return;
        }
        RepositoryContextFiles.WriteAtomically(destination, source);

        void FinishObject()
        {
            source.Append("}\n");
        }
    }

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
