using System.Globalization;
using System.Text;

namespace Nextorm.Contexts.ClickHouse;

public sealed record ClickHouseColumn(string Name, string NativeType);
public sealed record ClickHouseCatalogObject(string Database, string Name, bool IsView, IReadOnlyList<ClickHouseColumn> Columns);

public static class ClickHouseSchemaGenerator
{
    // Opt-in entry point for native catalog descriptions; no connection or default-mode change.
    public static void GenerateFromCatalog(string database, string table,
        IReadOnlyList<ClickHouseColumn> columns, string outputPath)
    {
        ArgumentNullException.ThrowIfNull(columns);
        WriteMappings([new(database, table, false, columns)], outputPath, useLegacyClassName: true);
    }

    public static void GenerateFromCatalog(IReadOnlyList<ClickHouseCatalogObject> objects, string outputPath) =>
        WriteMappings(objects, outputPath, useLegacyClassName: false);

    private static void WriteMappings(IReadOnlyList<ClickHouseCatalogObject> objects, string outputPath, bool useLegacyClassName)
    {
        ArgumentNullException.ThrowIfNull(objects);
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace ClickHouseDatabaseMappings;\n");
        var mappings = new List<string>(objects.Count);
        for (var index = 0; index < objects.Count; index++)
        {
            var name = useLegacyClassName ? "MappedTable" : FormattableString.Invariant($"MappedObject{index + 1}");
            AppendMapping(source, objects[index], name);
            mappings.Add(name);
        }
        RepositoryContextSource.Append(source, "ClickHouseRepositoryContext", mappings);

        RepositoryContextFiles.WriteAtomically(destination, source);
    }

    private static void AppendMapping(StringBuilder source, ClickHouseCatalogObject item, string className)
    {
        var (database, table, isView, columns) = item;
        ArgumentNullException.ThrowIfNull(columns);
        if (isView)
            source.Append("\n[global::System.ComponentModel.Description(\"ClickHouse VIEW\")]");
        source.Append(CultureInfo.InvariantCulture,
            $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(table)}, Schema = {Literal(database)})]\ninternal class {className}\n{{\n");
        var names = new HashSet<string>(StringComparer.Ordinal);
        var ordinal = 0;
        foreach (var column in columns)
        {
            if (!names.Add(column.Name))
                throw new InvalidDataException($"ClickHouse object {Literal(database)}.{Literal(table)}: duplicate column {Literal(column.Name)}.");

            var clrType = column.NativeType switch
            {
                "Int8" => "sbyte",
                "UInt8" => "byte",
                "Int16" => "short",
                "UInt16" => "ushort",
                "Int32" => "int",
                "UInt32" => "uint",
                "Int64" => "long",
                "UInt64" => "ulong",
                // Native String permits arbitrary bytes, not just Unicode text.
                "String" => "byte[]",
                _ => throw new InvalidDataException(
                    $"ClickHouse object {Literal(database)}.{Literal(table)}, column {Literal(column.Name)}: unsupported schema type {Literal(column.NativeType)}.")
            };
            var initializer = clrType == "byte[]" ? " = [];" : "";
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column.Name)}, TypeName = {Literal(column.NativeType)})]\n    public {clrType} Column{++ordinal} {{ get; set; }}{initializer}\n");
        }

        if (ordinal == 0)
            throw new InvalidDataException("ClickHouse table metadata must contain at least one column.");
        source.Append("}\n");
    }

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
