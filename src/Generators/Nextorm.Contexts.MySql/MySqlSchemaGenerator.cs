using MySqlConnector;
using System.Globalization;
using System.Text;

namespace Nextorm.Contexts.MySql;

public sealed record MySqlColumn(string Name, string Declaration, bool IsNullable);
public sealed record MySqlTable(string Name, IReadOnlyList<MySqlColumn> Columns, IReadOnlyList<string> PrimaryKey);

public static class MySqlSchemaGenerator
{
    public static void Scaffold(string connectionString, string schema, string outputPath,
        string targetNamespace, string contextName) =>
        Scaffold(connectionString, schema, outputPath, targetNamespace, contextName, null, null, null, null);

    public static void Scaffold(string connectionString, string schema, string outputPath,
        string targetNamespace, string contextName, global::Nextorm.Scaffold.IScaffoldInterceptor interceptor, bool singleFile = false) =>
        Scaffold(connectionString, schema, outputPath, targetNamespace, contextName,
            interceptor.IncludeObject, interceptor.GetEntityName, interceptor.GetPropertyName, interceptor.GetClrType, singleFile);

    public static void Scaffold(string connectionString, string schema, string outputPath,
        string targetNamespace, string contextName, Func<string, bool>? include, Func<string, string>? entityName,
        Func<string, string, string>? propertyName, Func<string, string, string?>? clrType, bool singleFile = false)
    {
        using var connection = new MySqlConnection(connectionString);
        connection.Open();
        if (connection.ServerVersion.Contains("MariaDB", StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("MySQL scaffolding requires a MySQL server.");
        using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT c.TABLE_NAME, c.COLUMN_NAME, c.COLUMN_TYPE, c.IS_NULLABLE, c.COLUMN_KEY
            FROM information_schema.COLUMNS c
            JOIN information_schema.TABLES t USING (TABLE_SCHEMA, TABLE_NAME)
            WHERE c.TABLE_SCHEMA = @schema AND t.TABLE_TYPE = 'BASE TABLE'
            ORDER BY BINARY c.TABLE_NAME, c.ORDINAL_POSITION
            """;
        command.Parameters.AddWithValue("@schema", schema);
        using var reader = command.ExecuteReader();
        var tables = new Dictionary<string, (List<MySqlColumn> Columns, List<string> Keys)>(StringComparer.Ordinal);
        while (reader.Read())
        {
            var table = reader.GetString(0);
            if (!tables.TryGetValue(table, out var mapping))
                tables.Add(table, mapping = ([], []));
            var column = reader.GetString(1);
            mapping.Columns.Add(new(column, reader.GetString(2), reader.GetString(3) == "YES"));
            if (reader.GetString(4) == "PRI")
                mapping.Keys.Add(column);
        }
        GenerateTables(schema,
            tables.Select(pair => new MySqlTable(pair.Key, pair.Value.Columns, pair.Value.Keys)).ToArray(),
            outputPath, targetNamespace, contextName, !singleFile, include, entityName, propertyName, clrType);
    }

    // Columns are supplied in catalog ordinal order. A null key denotes a table with no declared key.
    public static void Generate(string schema, string table, IReadOnlyList<MySqlColumn> columns,
        string? primaryKeyColumn, string outputPath) =>
        GenerateMapping(schema, table, columns, primaryKeyColumn, outputPath, isView: false);

    internal static void GenerateViewMapping(string schema, string view, IReadOnlyList<MySqlColumn> columns,
        string outputPath) =>
        GenerateMapping(schema, view, columns, null, outputPath, isView: true);

    private static void GenerateMapping(string schema, string table, IReadOnlyList<MySqlColumn> columns,
        string? primaryKeyColumn, string outputPath, bool isView)
    {
        ArgumentNullException.ThrowIfNull(columns);
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace MySqlDatabaseMappings;\n");
        var mappingName = isView ? "MappedView" : "MappedTable";
        AppendMapping(source, schema, table, columns, primaryKeyColumn is null ? [] : [primaryKeyColumn], mappingName, isView, false);
        RepositoryContextSource.Append(source, "MySqlRepositoryContext", [mappingName]);
        Publish(destination, source);
    }

    public static void GenerateTables(string schema, IReadOnlyList<MySqlTable> tables, string outputPath,
        string targetNamespace, string contextName) =>
        GenerateTables(schema, tables, outputPath, targetNamespace, contextName, splitModels: false);

    public static void Scaffold(string schema, IReadOnlyList<MySqlTable> tables, string outputPath,
        string targetNamespace, string contextName) =>
        GenerateTables(schema, tables, outputPath, targetNamespace, contextName, splitModels: true);

    public static void Scaffold(string schema, IReadOnlyList<MySqlTable> tables, string outputPath,
        string targetNamespace, string contextName, global::Nextorm.Scaffold.IScaffoldInterceptor interceptor, bool singleFile = false) =>
        GenerateTables(schema, tables, outputPath, targetNamespace, contextName, !singleFile,
            interceptor.IncludeObject, interceptor.GetEntityName, interceptor.GetPropertyName, interceptor.GetClrType);

    public static void Scaffold(string schema, IReadOnlyList<MySqlTable> tables, string outputPath,
        string targetNamespace, string contextName, Func<string, bool>? include, Func<string, string>? entityName,
        Func<string, string, string>? propertyName, Func<string, string, string?>? clrType) =>
        GenerateTables(schema, tables, outputPath, targetNamespace, contextName, true, include, entityName, propertyName, clrType);

    internal static void GenerateTables(string schema, IReadOnlyList<MySqlTable> tables, string outputPath,
        string targetNamespace, string contextName, bool splitModels, Func<string, bool>? include = null,
        Func<string, string>? renameEntity = null, Func<string, string, string>? renameProperty = null,
        Func<string, string, string?>? clrType = null)
    {
        if (tables.Count == 0)
            throw new InvalidDataException("No tables were found.");
        var source = new StringBuilder($"// <auto-generated/>\n#nullable enable\nnamespace {targetNamespace};\n");
        var names = new List<string>();
        var usedNames = new HashSet<string>(StringComparer.Ordinal) { contextName, "Repository" };
        foreach (var table in tables)
        {
            if (include is not null && !include(table.Name))
                continue;
            var name = RepositoryContextSource.Identifier(renameEntity?.Invoke(table.Name) ?? table.Name, "Entity", usedNames);
            AppendMapping(source, schema, table.Name, table.Columns, table.PrimaryKey, name, false, true, renameProperty, clrType);
            names.Add(name);
        }
        RepositoryContextSource.Append(source, contextName, names, publicContext: true);
        var destination = Path.GetFullPath(outputPath);
        if (splitModels)
            RepositoryContextFiles.Split(source.ToString(), destination);
        else
            Publish(destination, source);
    }

    private static void AppendMapping(StringBuilder source, string schema, string table, IReadOnlyList<MySqlColumn> columns,
        IReadOnlyList<string> primaryKey, string mappingName, bool isView, bool publicMapping,
        Func<string, string, string>? renameProperty = null, Func<string, string, string?>? clrType = null)
    {
        if (isView)
            source.Append("\n[global::System.ComponentModel.Description(\"MySQL VIEW\")]");
        var visibility = publicMapping ? "public" : "internal";
        var schemaArgument = publicMapping ? "" : $", Schema = {Literal(schema)}";
        source.Append(CultureInfo.InvariantCulture,
            $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(table)}{schemaArgument})]\n{visibility} class {mappingName}\n{{\n");
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var usedProperties = new HashSet<string>(StringComparer.Ordinal) { mappingName };
        var remainingKeys = new HashSet<string>(primaryKey, StringComparer.OrdinalIgnoreCase);
        var ordinal = 0;
        foreach (var column in columns)
        {
            if (!names.Add(column.Name))
                throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: duplicate column {Literal(column.Name)}.");

            var declaration = column.Declaration.Trim().ToLowerInvariant();
            var type = clrType?.Invoke(column.Name, column.Declaration) ?? (declaration switch
            {
                "int" => "int",
                "int unsigned" => "uint",
                "bigint" => "long",
                "bigint unsigned" => "ulong",
                "smallint" => "short",
                "smallint unsigned" => "ushort",
                "text" or "tinytext" or "mediumtext" or "longtext" => "string",
                "datetime" => "global::System.DateTime",
                _ when IsVarchar(declaration) => "string",
                _ => throw new InvalidDataException(
                    $"MySQL object {Literal(schema)}.{Literal(table)}, column {Literal(column.Name)}: unsupported schema type {Literal(column.Declaration)}.")
            });
            if (remainingKeys.Remove(column.Name))
            {
                if (column.IsNullable)
                    throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: primary key column {Literal(column.Name)} is nullable.");
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            }

            var suffix = column.IsNullable ? "?" : "";
            var initializer = !column.IsNullable && type == "string" ? " = null!;" : "";
            var property = publicMapping
                ? RepositoryContextSource.Identifier(renameProperty?.Invoke(table, column.Name) ?? column.Name, "Field", usedProperties)
                : FormattableString.Invariant($"Column{++ordinal}");
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column.Name)}, TypeName = {Literal(column.Declaration)})]\n    public {type}{suffix} {property} {{ get; set; }}{initializer}\n");
        }

        if (remainingKeys.Count > 0)
            throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: primary key column {Literal(remainingKeys.First())} was not found.");
        source.Append("}\n");
    }

    private static void Publish(string destination, StringBuilder source)
    {
        // Validate the complete mapping before opening any destination or temporary file.
        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        var ownsTemporary = false;
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            {
                ownsTemporary = true;
                using var writer = new StreamWriter(stream);
                writer.Write(source.ToString());
            }
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            if (ownsTemporary)
                File.Delete(temporary);
        }
    }

    private static bool IsVarchar(string declaration) =>
        declaration.StartsWith("varchar(", StringComparison.Ordinal) && declaration.EndsWith(')') &&
        int.TryParse(declaration.AsSpan(8, declaration.Length - 9), NumberStyles.None,
            CultureInfo.InvariantCulture, out var length) && length is >= 1 and <= 65535;

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
