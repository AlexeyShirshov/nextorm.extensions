using System.CommandLine;
using System.Xml;
using Nextorm.Contexts.OData;

namespace Nextorm.Scaffold;

internal static class ODataModelsCommand
{
    private const string Owner = "// Generated by dotnet-nextorm odata-models";

    internal static Command Create()
    {
        var metadata = new Option<string>("--metadata")
        {
            Description = "The HTTP(S) metadata URL or path to an EDMX XML file.",
            Required = true,
        };
        var targetNamespace = new Option<string>("--namespace")
        {
            Description = "The C# namespace prefix for the OData schema namespaces.",
            Required = true,
        };
        var output = new Option<string>("--output") { Description = "The output C# file path.", Required = true };
        var force = new Option<bool>("--force") { Description = "Replace a file generated by this command." };
        var command = new Command("odata-models", "Generate C# models from OData 4.0 or 4.01 XML metadata.")
        {
            metadata, targetNamespace, output, force,
        };
        command.SetAction((result, cancellationToken) => RunAsync(result.GetValue(metadata)!,
            result.GetValue(targetNamespace)!, result.GetValue(output)!, result.GetValue(force), cancellationToken));
        return command;
    }

    private static async Task<int> RunAsync(string metadata, string targetNamespace, string output, bool force,
        CancellationToken cancellationToken)
    {
        try
        {
            var path = Path.GetFullPath(output);
            var replace = File.Exists(path);
            if (replace)
            {
                if (!force)
                {
                    throw new IOException($"'{path}' already exists. Use --force to replace a generated file.");
                }
                using var existing = File.OpenText(path);
                if (await existing.ReadLineAsync(cancellationToken) != Owner)
                {
                    throw new IOException($"Refusing to overwrite '{path}': it was not generated by odata-models.");
                }
            }

            var source = await GenerateAsync(metadata, targetNamespace, cancellationToken);
            var directory = Path.GetDirectoryName(path)!;
            Directory.CreateDirectory(directory);
            var temporary = Path.Combine(directory, Path.GetRandomFileName());
            var created = false;
            try
            {
                await using (var writer = new StreamWriter(temporary, new FileStreamOptions
                {
                    Mode = FileMode.CreateNew,
                    Access = FileAccess.Write,
                    Options = FileOptions.Asynchronous,
                }))
                {
                    created = true;
                    await writer.WriteLineAsync(Owner.AsMemory(), cancellationToken);
                    await writer.WriteAsync(source.AsMemory(), cancellationToken);
                }

                cancellationToken.ThrowIfCancellationRequested();
                File.Move(temporary, path, overwrite: replace);
            }
            finally
            {
                if (created)
                {
                    File.Delete(temporary);
                }
            }
            Console.WriteLine($"Generated {path}.");
            return 0;
        }
        catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
        {
            Console.Error.WriteLine("The metadata request timed out.");
            return 1;
        }
        catch (Exception error) when (error is IOException or InvalidDataException or XmlException or
            HttpRequestException or ArgumentException or UnauthorizedAccessException or NotSupportedException)
        {
            Console.Error.WriteLine(error.Message);
            return 1;
        }
    }

    private static async Task<string> GenerateAsync(string metadata, string targetNamespace,
        CancellationToken cancellationToken)
    {
        if (Uri.TryCreate(metadata, UriKind.Absolute, out var url) && !url.IsFile)
        {
            if (url.Scheme is not ("http" or "https") || url.UserInfo.Length > 0)
            {
                throw new ArgumentException("Use an HTTP(S) metadata URL without embedded credentials, or a local XML file.");
            }
            using var client = new HttpClient { MaxResponseContentBufferSize = 16 * 1024 * 1024 };
            client.DefaultRequestHeaders.Accept.ParseAdd("application/xml");
            using var response = await client.GetAsync(url, cancellationToken);
            response.EnsureSuccessStatusCode();
            using var downloaded = await response.Content.ReadAsStreamAsync(cancellationToken);
            return ODataModelGenerator.Generate(downloaded, targetNamespace);
        }

        using var file = File.OpenRead(metadata);
        return ODataModelGenerator.Generate(file, targetNamespace);
    }
}
