using System.Globalization;
using System.Text;

namespace Nextorm.Contexts.MariaDb;

public sealed record MariaDbColumn(string Name, string Declaration, bool IsNullable);

public enum MariaDbObjectKind { BaseTable = 1, View }

public static class MariaDbSchemaGenerator
{
    public static void Generate(string schema, string table, IReadOnlyList<MariaDbColumn> columns,
        string primaryKeyColumn, string outputPath)
    {
        ArgumentNullException.ThrowIfNull(primaryKeyColumn);
        Generate(schema, table, columns, MariaDbObjectKind.BaseTable, primaryKeyColumn, outputPath);
    }

    public static void Generate(string schema, string table, IReadOnlyList<MariaDbColumn> columns,
        MariaDbObjectKind kind, string? primaryKeyColumn, string outputPath)
    {
        if (kind is not (MariaDbObjectKind.BaseTable or MariaDbObjectKind.View))
            throw new ArgumentOutOfRangeException(nameof(kind));
        if (kind == MariaDbObjectKind.View && primaryKeyColumn is not null)
            throw new ArgumentException("A MariaDB view has no declared primary key.", nameof(primaryKeyColumn));
        GenerateMapping(schema, table, columns, kind, primaryKeyColumn is null ? [] : [primaryKeyColumn], outputPath);
    }

    public static void GenerateComposite(string schema, string table, IReadOnlyList<MariaDbColumn> columns,
        IReadOnlyList<string> primaryKeyColumns, string outputPath)
    {
        ArgumentNullException.ThrowIfNull(primaryKeyColumns);
        if (primaryKeyColumns.Count < 2)
            throw new InvalidDataException($"MariaDB object {Literal(schema)}.{Literal(table)}: a composite primary key requires at least two columns.");
        GenerateMapping(schema, table, columns, MariaDbObjectKind.BaseTable, primaryKeyColumns, outputPath);
    }

    private static void GenerateMapping(string schema, string table, IReadOnlyList<MariaDbColumn> columns,
        MariaDbObjectKind kind, IReadOnlyList<string> primaryKeyColumns, string outputPath)
    {
        ArgumentNullException.ThrowIfNull(columns);
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var objectName = $"{Literal(schema)}.{Literal(table)}";
        var keyOrdinals = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        for (var index = 0; index < primaryKeyColumns.Count; index++)
        {
            var member = primaryKeyColumns[index];
            if (primaryKeyColumns.Count > 1 && string.IsNullOrWhiteSpace(member))
                throw new InvalidDataException($"MariaDB object {objectName}: primary key member {index + 1} is empty.");
            if (!keyOrdinals.TryAdd(member, index))
                throw new InvalidDataException($"MariaDB object {objectName}: duplicate primary key column {Literal(member)}.");
        }
        var keyProperties = new int?[keyOrdinals.Count];
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace MariaDbDatabaseMappings;\n");
        if (kind == MariaDbObjectKind.View)
            source.Append("\n[global::System.ComponentModel.Description(\"MariaDB VIEW\")]");
        var className = kind == MariaDbObjectKind.View ? "MappedView" : "MappedTable";
        var attributeOffset = source.Length;
        source.Append(CultureInfo.InvariantCulture,
            $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(table)}, Schema = {Literal(schema)})]\ninternal sealed class {className}\n{{\n");
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var ordinal = 0;
        foreach (var column in columns)
        {
            if (!names.Add(column.Name))
                throw new InvalidDataException($"MariaDB object {objectName}: duplicate column {Literal(column.Name)}.");

            var declaration = column.Declaration.Trim().ToLowerInvariant();
            var type = declaration switch
            {
                "int" or "int(11)" or "mediumint" or "mediumint(9)" => "int",
                "int unsigned" or "int(10) unsigned" or "mediumint unsigned" or "mediumint(8) unsigned" => "uint",
                "bigint" or "bigint(20)" => "long",
                "bigint unsigned" or "bigint(20) unsigned" => "ulong",
                "text" => "string",
                _ when IsVarchar(declaration) => "string",
                _ => throw new InvalidDataException(
                    $"MariaDB object {objectName}, column {Literal(column.Name)}: unsupported schema type {Literal(column.Declaration)}.")
            };
            if (keyOrdinals.TryGetValue(column.Name, out var keyOrdinal))
            {
                if (column.IsNullable)
                    throw new InvalidDataException($"MariaDB object {objectName}: primary key column {Literal(column.Name)} is nullable.");
                keyProperties[keyOrdinal] = ordinal + 1;
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            }

            var suffix = column.IsNullable ? "?" : "";
            var initializer = !column.IsNullable && type == "string" ? " = null!;" : "";
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column.Name)}, TypeName = {Literal(column.Declaration)})]\n    public {type}{suffix} Column{++ordinal} {{ get; set; }}{initializer}\n");
        }

        for (var index = 0; index < keyProperties.Length; index++)
            if (keyProperties[index] is null)
                throw new InvalidDataException($"MariaDB object {objectName}: primary key column {Literal(primaryKeyColumns[index])} was not found.");
        source.Append("}\n");
        if (keyProperties.Length > 1)
        {
            var members = string.Join(", ", keyProperties.Select(property =>
                FormattableString.Invariant($"nameof(MappedTable.Column{property})")));
            source.Insert(attributeOffset, $"\n[CompositePrimaryKey({members})]");
            source.Append("""

                [global::System.AttributeUsage(global::System.AttributeTargets.Class)]
                internal sealed class CompositePrimaryKeyAttribute(params string[] members) : global::System.Attribute
                {
                    public global::System.Collections.Generic.IReadOnlyList<string> Members { get; } =
                        global::System.Array.AsReadOnly(members);
                }

                """);
        }

        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        var ownsTemporary = false;
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            {
                ownsTemporary = true;
                using var writer = new StreamWriter(stream);
                writer.Write(source.ToString());
            }
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            if (ownsTemporary)
                File.Delete(temporary);
        }
    }

    private static bool IsVarchar(string declaration) =>
        declaration.StartsWith("varchar(", StringComparison.Ordinal) && declaration.EndsWith(')') &&
        int.TryParse(declaration.AsSpan(8, declaration.Length - 9), NumberStyles.None,
            CultureInfo.InvariantCulture, out var length) && length is >= 1 and <= 65535;

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
