using System.Globalization;
using System.Text;

namespace Nextorm.Contexts.MySql;

public sealed record MySqlColumn(string Name, string Declaration, bool IsNullable);

public static class MySqlSchemaGenerator
{
    // Columns are supplied in catalog ordinal order. A null key denotes a table with no declared key.
    public static void Generate(string schema, string table, IReadOnlyList<MySqlColumn> columns,
        string? primaryKeyColumn, string outputPath)
    {
        ArgumentNullException.ThrowIfNull(columns);
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace MySqlDatabaseMappings;\n");
        source.Append(CultureInfo.InvariantCulture,
            $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(table)}, Schema = {Literal(schema)})]\ninternal sealed class MappedTable\n{{\n");
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var keyFound = false;
        var ordinal = 0;
        foreach (var column in columns)
        {
            if (!names.Add(column.Name))
                throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: duplicate column {Literal(column.Name)}.");

            var declaration = column.Declaration.Trim().ToLowerInvariant();
            var type = declaration switch
            {
                "int" => "int",
                "int unsigned" => "uint",
                "bigint" => "long",
                "bigint unsigned" => "ulong",
                "smallint" => "short",
                "smallint unsigned" => "ushort",
                "text" => "string",
                _ when IsVarchar(declaration) => "string",
                _ => throw new InvalidDataException(
                    $"MySQL object {Literal(schema)}.{Literal(table)}, column {Literal(column.Name)}: unsupported schema type {Literal(column.Declaration)}.")
            };
            if (StringComparer.OrdinalIgnoreCase.Equals(column.Name, primaryKeyColumn))
            {
                if (column.IsNullable)
                    throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: primary key column {Literal(column.Name)} is nullable.");
                keyFound = true;
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            }

            var suffix = column.IsNullable ? "?" : "";
            var initializer = !column.IsNullable && type == "string" ? " = null!;" : "";
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column.Name)}, TypeName = {Literal(column.Declaration)})]\n    public {type}{suffix} Column{++ordinal} {{ get; set; }}{initializer}\n");
        }

        if (primaryKeyColumn is not null && !keyFound)
            throw new InvalidDataException($"MySQL object {Literal(schema)}.{Literal(table)}: primary key column {Literal(primaryKeyColumn)} was not found.");
        source.Append("}\n");

        // Validate the complete mapping before opening any destination or temporary file.
        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        var ownsTemporary = false;
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            {
                ownsTemporary = true;
                using var writer = new StreamWriter(stream);
                writer.Write(source.ToString());
            }
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            if (ownsTemporary)
                File.Delete(temporary);
        }
    }

    private static bool IsVarchar(string declaration) =>
        declaration.StartsWith("varchar(", StringComparison.Ordinal) && declaration.EndsWith(')') &&
        int.TryParse(declaration.AsSpan(8, declaration.Length - 9), NumberStyles.None,
            CultureInfo.InvariantCulture, out var length) && length is >= 1 and <= 65535;

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
