using System.Globalization;
using System.Text;
using Npgsql;

namespace Nextorm.Contexts.PostgreSql;

public static class PostgreSqlSchemaGenerator
{
    public static void Generate(string connectionString, string outputPath)
    {
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        using var connection = new NpgsqlConnection(connectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT c.oid, n.nspname, c.relname, a.attname,
                   pg_catalog.format_type(a.atttypid, a.atttypmod),
                   CASE WHEN tn.nspname = 'pg_catalog' THEN t.typname END,
                   a.attnotnull, COALESCE(k.ordinality, 0)
            FROM pg_catalog.pg_class AS c
            JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
            LEFT JOIN pg_catalog.pg_attribute AS a
              ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
            LEFT JOIN pg_catalog.pg_type AS t ON t.oid = a.atttypid
            LEFT JOIN pg_catalog.pg_namespace AS tn ON tn.oid = t.typnamespace
            LEFT JOIN pg_catalog.pg_index AS i ON i.indrelid = c.oid AND i.indisprimary
              AND c.relkind IN ('r', 'p', 'f')
            LEFT JOIN LATERAL pg_catalog.unnest(i.indkey) WITH ORDINALITY AS k(attnum, ordinality)
              ON k.attnum = a.attnum AND k.ordinality <= i.indnkeyatts
            WHERE c.relkind IN ('r', 'p', 'f', 'v', 'm')
              AND n.nspname NOT IN ('pg_catalog', 'information_schema')
              AND n.nspname !~ '^pg_(toast|temp_)'
            ORDER BY n.nspname COLLATE "C", c.relname COLLATE "C", a.attnum
            """;

        using var reader = command.ExecuteReader();
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace PostgreSqlDatabaseMappings;\n");
        uint? previous = null;
        var objectNumber = 0;
        var columnNumber = 0;
        while (reader.Read())
        {
            var id = reader.GetFieldValue<uint>(0);
            var schema = reader.GetString(1);
            var name = reader.GetString(2);
            if (id != previous)
            {
                if (previous.HasValue)
                    source.Append("}\n");
                previous = id;
                columnNumber = 0;
                source.Append(CultureInfo.InvariantCulture,
                    $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(name)}, Schema = {Literal(schema)})]\ninternal sealed class Object{++objectNumber}\n{{\n");
            }

            if (reader.IsDBNull(3))
                continue;

            var column = reader.GetString(3);
            var declaration = reader.GetString(4);
            var type = (reader.IsDBNull(5) ? null : reader.GetString(5)) switch
            {
                "bool" => "bool",
                "int2" => "short",
                "int4" => "int",
                "int8" => "long",
                "float4" => "float",
                "float8" => "double",
                "text" or "varchar" or "bpchar" => "string",
                "bytea" => "byte[]",
                "uuid" => "global::System.Guid",
                _ => throw new InvalidDataException(
                    $"PostgreSQL object {Literal(schema)}.{Literal(name)}, column {Literal(column)}: unsupported schema type {Literal(declaration)}.")
            };

            var notNull = reader.GetBoolean(6);
            var suffix = notNull ? "" : "?";
            var initializer = notNull && type is "string" or "byte[]" ? " = null!;" : "";
            if (reader.GetInt64(7) > 0)
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column)}, TypeName = {Literal(declaration)})]\n    public {type}{suffix} Column{++columnNumber} {{ get; set; }}{initializer}\n");
        }

        if (previous.HasValue)
            source.Append("}\n");

        // An unsupported declaration fails before opening any output file.
        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        var ownsTemporary = false;
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            {
                ownsTemporary = true;
                using var writer = new StreamWriter(stream);
                writer.Write(source.ToString());
            }
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            if (ownsTemporary)
                File.Delete(temporary);
        }
    }

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
