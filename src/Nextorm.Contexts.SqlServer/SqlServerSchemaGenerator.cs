using System.Data.Common;
using System.Globalization;
using System.Text;
using Microsoft.Data.SqlClient;

namespace Nextorm.Contexts.SqlServer;

public static class SqlServerSchemaGenerator
{
    public static void Generate(string connectionString, string outputPath)
    {
        using var connection = new SqlConnection(connectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT o.object_id, s.name, o.name, c.name, ts.name, t.name,
                   c.is_nullable, c.precision, c.scale, c.max_length,
                   CONVERT(int, COALESCE(ic.key_ordinal, 0)),
                   CONVERT(bit, CASE WHEN t.is_user_defined = 1 OR t.is_assembly_type = 1 THEN 1 ELSE 0 END),
                   o.type
            FROM sys.objects AS o
            JOIN sys.schemas AS s ON s.schema_id = o.schema_id
            LEFT JOIN sys.columns AS c ON c.object_id = o.object_id
            LEFT JOIN sys.types AS t ON t.user_type_id = c.user_type_id
            LEFT JOIN sys.schemas AS ts ON ts.schema_id = t.schema_id
            LEFT JOIN sys.indexes AS i ON i.object_id = o.object_id AND i.is_primary_key = 1 AND o.type = 'U'
            LEFT JOIN sys.index_columns AS ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
                AND ic.column_id = c.column_id AND ic.key_ordinal > 0
            WHERE o.type IN ('U', 'V', 'ET') AND o.is_ms_shipped = 0
            ORDER BY o.object_id, c.column_id
            """;
        using var reader = command.ExecuteReader();
        WriteMappings(reader, outputPath, hasCatalogKind: true);
    }

    internal static void WriteMappings(DbDataReader metadata, string outputPath) =>
        WriteMappings(metadata, outputPath, hasCatalogKind: false);

    private static void WriteMappings(DbDataReader metadata, string outputPath, bool hasCatalogKind)
    {
        var destination = Path.GetFullPath(outputPath);
        if (!destination.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            throw new ArgumentException("Output must be a C# source file.", nameof(outputPath));

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace SqlServerDatabaseMappings;\n");
        int? previous = null;
        var objectNumber = 0;
        var columnNumber = 0;
        var attributeOffset = 0;
        var keyMembers = new SortedDictionary<int, int>();
        var hasCompositeKey = false;
        while (metadata.Read())
        {
            var id = metadata.GetInt32(0);
            var schema = metadata.GetString(1);
            var name = metadata.GetString(2);
            if (id != previous)
            {
                if (previous.HasValue)
                    FinishObject();
                previous = id;
                columnNumber = 0;
                attributeOffset = source.Length;
                if (hasCatalogKind)
                {
                    var kind = metadata.GetString(12).TrimEnd() switch
                    {
                        "U" => "TABLE",
                        "V" => "VIEW",
                        "ET" => "EXTERNAL TABLE",
                        _ => throw new InvalidDataException("Unexpected SQL Server catalog object kind.")
                    };
                    source.Append(CultureInfo.InvariantCulture,
                        $"\n[global::System.ComponentModel.Description({Literal("SQL Server " + kind)})]");
                }
                source.Append(CultureInfo.InvariantCulture,
                    $"\n[global::System.ComponentModel.DataAnnotations.Schema.Table({Literal(name)}, Schema = {Literal(schema)})]\ninternal sealed class Object{++objectNumber}\n{{\n");
            }

            if (metadata.IsDBNull(3))
                continue;

            var column = metadata.GetString(3);
            var typeName = metadata.IsDBNull(5) ? "<unresolved catalog type>" : metadata.GetString(5);
            var precision = metadata.GetByte(7);
            var scale = metadata.GetByte(8);
            var length = metadata.GetInt16(9);
            var custom = metadata.GetBoolean(11);
            var declaration = custom ? $"{metadata.GetString(4)}.{typeName}" : typeName switch
            {
                "decimal" or "numeric" => FormattableString.Invariant($"{typeName}({precision},{scale})"),
                "datetime2" or "datetimeoffset" or "time" => FormattableString.Invariant($"{typeName}({scale})"),
                "nvarchar" or "nchar" => length < 0 ? $"{typeName}(max)" : FormattableString.Invariant($"{typeName}({length / 2})"),
                "varchar" or "char" or "varbinary" or "binary" => length < 0 ? $"{typeName}(max)" : FormattableString.Invariant($"{typeName}({length})"),
                _ => typeName
            };
            var type = (custom ? "" : typeName) switch
            {
                "bit" => "bool",
                "tinyint" => "byte",
                "smallint" => "short",
                "int" => "int",
                "bigint" => "long",
                "real" => "float",
                "float" => "double",
                "money" or "smallmoney" => "decimal",
                "decimal" or "numeric" when precision <= 28 => "decimal",
                "char" or "varchar" or "text" or "nchar" or "nvarchar" or "ntext" => "string",
                "binary" or "varbinary" or "image" or "timestamp" or "rowversion" => "byte[]",
                "uniqueidentifier" => "global::System.Guid",
                "date" or "datetime" or "datetime2" or "smalldatetime" => "global::System.DateTime",
                "datetimeoffset" => "global::System.DateTimeOffset",
                "time" => "global::System.TimeSpan",
                _ => throw new InvalidDataException(
                    $"SQL Server object {Literal(schema)}.{Literal(name)}, column {Literal(column)}: unsupported schema type {Literal(declaration)}.")
            };
            var nullable = metadata.GetBoolean(6);
            var suffix = nullable ? "?" : "";
            var initializer = !nullable && type is "string" or "byte[]" ? " = null!;" : "";
            var keyOrdinal = metadata.GetInt32(10);
            if (keyOrdinal > 0)
            {
                keyMembers.Add(keyOrdinal, columnNumber + 1);
                source.Append("    [global::System.ComponentModel.DataAnnotations.Key]\n");
            }
            source.Append(CultureInfo.InvariantCulture,
                $"    [global::System.ComponentModel.DataAnnotations.Schema.Column({Literal(column)}, TypeName = {Literal(declaration)})]\n    public {type}{suffix} Column{++columnNumber} {{ get; set; }}{initializer}\n");
        }

        if (previous.HasValue)
            FinishObject();

        if (hasCompositeKey)
            source.Append("""

                [global::System.AttributeUsage(global::System.AttributeTargets.Class)]
                internal sealed class CompositePrimaryKeyAttribute(params string[] members) : global::System.Attribute
                {
                    public global::System.Collections.Generic.IReadOnlyList<string> Members { get; } =
                        global::System.Array.AsReadOnly(members);
                }

                """);

        var temporary = Path.Combine(Path.GetDirectoryName(destination)!, $".{Guid.NewGuid():N}.tmp");
        var ownsTemporary = false;
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew, FileAccess.Write))
            {
                ownsTemporary = true;
                using var writer = new StreamWriter(stream);
                writer.Write(source.ToString());
            }
            File.Move(temporary, destination, overwrite: true);
        }
        finally
        {
            if (ownsTemporary)
                File.Delete(temporary);
        }

        void FinishObject()
        {
            if (keyMembers.Count > 1)
            {
                var members = string.Join(", ", keyMembers.Values.Select(member =>
                    FormattableString.Invariant($"nameof(Object{objectNumber}.Column{member})")));
                source.Insert(attributeOffset, $"\n[CompositePrimaryKey({members})]");
                hasCompositeKey = true;
            }
            keyMembers.Clear();
            source.Append("}\n");
        }
    }

    private static string Literal(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is >= ' ' and <= '~' and not '"' and not '\\')
                result.Append(character);
            else
                result.Append(CultureInfo.InvariantCulture, $"\\u{(int)character:x4}");
        }
        return result.Append('"').ToString();
    }
}
